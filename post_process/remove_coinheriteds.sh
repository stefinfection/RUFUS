# This script removes inherited variants called by rufus which lie on the same contig as
# a somatic variant. It accomplishes this task by performing a pileup and variant call
# in the control bam for each of the rufus-identified variants, then taking the complement
# of the control set in an intersection.

# parse command line arguments
REFERENCE_FILE=$1  # Reference file (.fa) - must be the same as RUFUS run that generated RUFUS_VCF
RUFUS_VCF=$2       # The 'FINAL' vcf generated by rufus, to be isec'd
OUT_VCF=$3
SRC_DIR=$4
WINDOW_SIZE=$5
ARG_LIST=("$@")
CONTROL_BAM_LIST=("${ARG_LIST[@]:5}") # Remaining args, all control bams

cd "$SRC_DIR" || exit 1

# static vars
CONTROL_ALIGNED="temp_aligned.bam"
CONTROL_VCF="isec_control.vcf.gz"
NORMED_VCF="normed.${RUFUS_VCF}"
BWA="/opt/RUFUS/bin/externals/bwa/src/bwa_project/bwa"
BCFTOOLS="/opt/bcftools/bcftools"
SAMTOOLS="/opt/samtools/samtools"
PILEUP_SCRIPT="/opt/RUFUS/post_process/single_pileup.sh"

# TODO: make cleanup and trap here

# Check we actually have variants
num_vars=$($BCFTOOLS view -H "$RUFUS_VCF" | wc -l)
if [ "$num_vars" -eq 0 ]; then
	echo "No variants found in rufus supplied vcf to remove_coinheriteds script - exiting..." >&2
	exit 1
fi

# make intersection directory
ISEC_OUT_DIR="temp_isecs"
mkdir -p $ISEC_OUT_DIR

#format final rufus vcf for intersections
vt normalize -n "$RUFUS_VCF" -r "$REFERENCE_FILE" | vt decompose_blocksub - | bgzip > "$NORMED_VCF"
$BCFTOOLS index -t "$NORMED_VCF"

#for loop for each control file provided by user
MERGED_PILEUP="merged_pileup.vcf.gz"
pileups=()
for CONTROL in "${CONTROL_BAM_LIST[@]}"; do
	echo "Piling up $CONTROL" >&2

    MADE_ALIGN_CONTROL=false
	CONTROL_BAM=""

	# Make temp dir for individual pileups
	CONTROL_TAG=$(basename "$CONTROL")
	CONTROL_TAG="${CONTROL_TAG%.bam}"
	CURR_MERGED_PILEUP="${CONTROL_TAG}.ctrl.merged_pileup.vcf.gz"
	CURR_PILEUP_DIR="${CONTROL_TAG}_temp_pileups"
 
    #check to see if the provided bam file is aligned
    if [ "$($SAMTOOLS view -H "$CONTROL" | grep -c '^@SQ')" -gt 0 ]; then
        CONTROL_BAM=$CONTROL
    else
		# todo: need to not hard code thread count here
        $BWA mem -t 10 "$REFERENCE_FILE" "$CONTROL" | $SAMTOOLS view -S -@ 12 -b - > $CONTROL_ALIGNED
        CONTROL_BAM=$CONTROL_ALIGNED
	    MADE_ALIGN_CONTROL=true
    fi
    
    # Run pileup and call variants
	echo "Starting parallel mpileup..."
	
	# Running in WG mode, split pileup by chr
	if [ "$WINDOW_SIZE" -ne 0 ]; then
		# Likely dealing with a small number of variants, send in a single list of sites
		regions=$($BCFTOOLS view -H "$NORMED_VCF" | awk '!/^#/ {printf "%s%s:%d-%d", sep, $1, $2, $2; sep=","} END{print ""}')
		bash $PILEUP_SCRIPT "$regions" "${CONTROL_BAM}" "${REFERENCE_FILE}" > "$CURR_MERGED_PILEUP"
	else
		# Better to do chromosome by chromosome for speed for entire genome
		mkdir -p "$CURR_PILEUP_DIR"
		$BCFTOOLS query -f '%CHROM\n' "$NORMED_VCF" | sort | uniq | \
		awk -v bam="$CONTROL_BAM" -v ref="$REFERENCE_FILE" '{print $1 "\t" bam "\t" ref}' > arguments.txt
		cat arguments.txt | parallel -j +0 --colsep '\t' "bash \"$PILEUP_SCRIPT\" {1} {2} {3} > $CURR_PILEUP_DIR/{1}.vcf.gz"
		for vcf in "$CURR_PILEUP_DIR"/*vcf.gz; do
			$BCFTOOLS index "$vcf"
		done
		# TODO: this needs to be tested - whole genome 
		$BCFTOOLS concat -Oz -o "$CURR_MERGED_PILEUP" "$CURR_PILEUP_DIR"/*.vcf.gz
		rm "arguments.txt"
		rm -r "$CURR_PILEUP_DIR"
	fi

	$BCFTOOLS index "$CURR_MERGED_PILEUP"
	pileups+=("$CURR_MERGED_PILEUP")
done

# Combine control specific pileups if there are mutliple
if [ "${#pileups[@]}" -gt 1 ]; then
	echo "about to merge"
	$BCFTOOLS merge -o "$MERGED_PILEUP" -Ov "${pileups[@]}"
else
	# TODO: this needs to be tested - single control in both modes
	cp "${pileups[0]}" "$MERGED_PILEUP"
fi
rm ./*ctrl.merged_pileup.vcf.gz*

# sort combined pileups
$BCFTOOLS sort -Oz -o "sorted.$MERGED_PILEUP" "$MERGED_PILEUP"
$BCFTOOLS index "sorted.$MERGED_PILEUP"
rm $MERGED_PILEUP

# call variants from merged pileup vcf
echo "Starting pileup call..."
$BCFTOOLS call -cv -Oz -o $CONTROL_VCF "sorted.$MERGED_PILEUP"
$BCFTOOLS index $CONTROL_VCF
rm "sorted.$MERGED_PILEUP"*

#intersect the control vcf with formatted rufus vcf
echo "Starting intersection..."
$BCFTOOLS isec -Oz -w1 -n=1 -p $ISEC_OUT_DIR "$NORMED_VCF" "$CONTROL_VCF"
$BCFTOOLS index "$ISEC_OUT_DIR/0000.vcf.gz"

# save the new vcf as rufus final vcf
OUTFILE="$ISEC_OUT_DIR/0000.vcf.gz"
OUT_INDEX="$ISEC_OUT_DIR/0000.vcf.gz.csi"

cp "$OUTFILE" "${OUT_VCF}" 
cp "$OUT_INDEX" "${OUT_VCF}.csi" 
rm "$CONTROL_VCF"*

# clean up aligned control file, if it exists
if [ "$MADE_ALIGN_CONTROL" == "true" ]; then
	rm $CONTROL_ALIGNED
fi
rm -r $ISEC_OUT_DIR